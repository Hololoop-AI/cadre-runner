"""Write a module's public API snapshot: every declaration its index.ts
exports, as the TypeScript compiler declares it, with its doc comment.
Design gate G5 regenerates these and fails on any difference; G4 fails on
any declaration marked `// (undocumented)`.

    python3 web/scripts/api_snapshot.py model     # rewrites web/api/model.api.d.ts
    python3 web/scripts/api_snapshot.py --all     # every module under web/src/

A module is a directory under web/src/ with an index.ts. Its public API is
exactly what index.ts names in `export { ... } from './file'` lines (or
declares itself); nothing else in the directory can be imported from
outside it (scripts/check_boundaries.mjs).
"""

import re
import subprocess
import sys
import tempfile
from pathlib import Path

WEB = Path(__file__).resolve().parents[1]
SRC = WEB / "src"
OUT = WEB / "api"
REEXPORT = re.compile(r"^export (?:type )?\{([^}]*)\} from '\./([^']+)';$", re.M | re.S)


def emit(out: Path) -> None:
    """Declaration files for all of src/, from the project's own compiler."""
    subprocess.run(["npx", "tsc", "-p", ".", "--declaration", "--emitDeclarationOnly",
                    "--noEmit", "false", "--outDir", str(out)], cwd=WEB, check=True)


def declarations(dts: str) -> dict[str, str]:
    """Top-level exported declarations of one .d.ts, by name, each with the
    doc comment right above it (or a `// (undocumented)` marker)."""
    out, doc, block, name = {}, "", [], None
    lines = dts.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("/**"):
            j = i
            while "*/" not in lines[j]:
                j += 1
            doc = "\n".join(lines[i:j + 1])
            i = j + 1
            continue
        m = re.match(r"export (?:declare )?(?:const|function|interface|type|class) (\w+)", line)
        if m:
            block = [line]
            j = i + 1
            # a block runs until the next line back at column 0
            while j < len(lines) and (lines[j].startswith((" ", "\t")) or lines[j] in ("}", "};", "]", "];")):
                block.append(lines[j])
                j += 1
            name = m.group(1)
            # one name may be declared twice (a function overload); keep both
            prev = out.get(name, "")
            out[name] = (prev + "\n" if prev else "") + (doc or "// (undocumented)") + "\n" + "\n".join(block)
            doc = ""
            i = j
            continue
        doc = ""
        i += 1
    return out


def snapshot(module: str, dts_root: Path) -> str:
    base = dts_root / "src" / module
    index = (base / "index.d.ts").read_text()
    parts = [f"// Public API of web/src/{module} — generated by web/scripts/api_snapshot.py; do not edit.\n"]
    own = declarations(index)
    for names, file in REEXPORT.findall(index):
        decls = declarations((base / f"{file}.d.ts").read_text())
        wanted = [n.strip().removeprefix("type ").strip() for n in names.split(",") if n.strip()]
        parts.append(f"// --- from {file}.ts")
        for n in wanted:
            parts.append(decls.get(n, f"// (not found in {file}.d.ts) {n}"))
    for n, text in own.items():
        parts.append(text)
    return "\n".join(parts) + "\n"


def modules() -> list[str]:
    return sorted(d.name for d in SRC.iterdir() if (d / "index.ts").is_file())


def main(argv: list[str]) -> int:
    wanted = modules() if argv[1:] == ["--all"] else argv[1:]
    if not wanted:
        print(__doc__)
        return 2
    OUT.mkdir(exist_ok=True)
    bad = 0
    with tempfile.TemporaryDirectory() as tmp:
        emit(Path(tmp))
        for module in wanted:
            text = snapshot(module, Path(tmp))
            (OUT / f"{module}.api.d.ts").write_text(text)
            print(f"wrote web/api/{module}.api.d.ts")
            # G4: every public symbol carries a doc comment
            n = sum(line.startswith(("// (undocumented)", "// (not found")) for line in text.splitlines())
            if n:
                print(f"{module}: {n} public symbol(s) undocumented or missing; see the snapshot", file=sys.stderr)
            bad += n
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
